package 算法题;

public class 第135题分发糖果 {
    public int candy(int[] ratings) {
        int n = ratings.length;
        // 总糖果数，初始化为1（第一个孩子至少分1颗）
        int ret = 1;
        // inc：当前递增序列的长度（记录连续评分上升时的糖果数）
        int inc = 1;
        // dec：当前递减序列的长度（记录连续评分下降时的糖果数）
        int dec = 0;
        // pre：前一个孩子分到的糖果数
        int pre = 1;

        // 从第二个孩子开始遍历（i从1开始）
        for (int i = 1; i < n; i++) {
            // 情况1：当前孩子评分 >= 前一个孩子的评分
            if (ratings[i] >= ratings[i - 1]) {
                // 递减序列重置（因为当前是上升/持平）
                dec = 0;
                // 若评分相等：当前孩子只需要1颗（满足“至少1颗”即可，无需比前一个多）
                // 若评分更高：当前孩子的糖果数 = 前一个+1
                pre = ratings[i] == ratings[i - 1] ? 1 : pre + 1;
                // 总糖果数累加当前孩子的糖果数
                ret += pre;
                // 更新递增序列长度为当前的pre（因为是连续上升）
                inc = pre;
            }
            // 情况2：当前孩子评分 < 前一个孩子的评分（进入递减序列）
            else {
                // 递减序列长度+1
                dec++;
                // 关键处理：当递减序列长度等于之前的递增序列长度时，
                // 需要把“递增序列的最后一个孩子”也纳入递减序列（多给1颗），避免冲突
                // 例如 [1,3,2]：递增序列是1→3（inc=2），递减序列是3→2（dec=1）→ 无需额外加；
                // 但 [1,4,3,2]：递增序列1→4（inc=2），递减序列4→3→2（dec=2），此时dec=inc，
                // 需要给4额外加1颗（否则3的糖果数会等于4，不满足“评分高的糖果多”）
                if (dec == inc) {
                    dec++;
                }
                // 递减序列中，当前孩子的糖果数=dec（因为是连续下降，每往后一个孩子多1颗）
                ret += dec;
                // 递减序列的最后一个孩子，下一个孩子的pre重置为1（因为递减序列的末尾至少1颗）
                pre = 1;
            }
        }
        return ret;
    }
}
